import type { RegionId } from "@/config/regions";
import type { Feature, MultiPolygon, Polygon } from "geojson";

export type ZoneId = "higashi-jujo" | "home-turf";

// "player" or a reference to the NPC currently holding the zone — reassignable
// later (raids, other gangs) without a schema change.
export type ZoneOwner = "player" | { npcId: string };

export type Zone = {
  id: ZoneId;
  region: RegionId;
  name: string;
  boundary: Feature<Polygon | MultiPolygon>;
  owner: ZoneOwner;
};

export const ZONE_COLORS = {
  player: { fillColor: "#44a684", fillOpacity: 0.4, lineColor: "#44a684", lineWidth: 2 },
  npc: { fillColor: "#a63d44", fillOpacity: 0.4, lineColor: "#a63d44", lineWidth: 2 },
} as const;

export function zoneStyle(owner: ZoneOwner) {
  return owner === "player" ? ZONE_COLORS.player : ZONE_COLORS.npc;
}

// A zone's static `owner` is its starting state. Capture is currently
// one-directional (NPC -> player, no raids/reclaiming yet), so the actual
// current owner is: "player" once captured, otherwise the static owner.
export function effectiveOwner(zone: Zone, capturedZoneIds: ZoneId[]): ZoneOwner {
  return capturedZoneIds.includes(zone.id) ? "player" : zone.owner;
}

